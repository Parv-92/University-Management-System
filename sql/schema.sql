-- ====================================================================
-- University Management System
-- Database Schema DDL (Oracle Database 23ai Free Compatible)
-- 
-- Description: Creates the 10 normalized relational tables with
--              Primary Keys, Foreign Keys, and Domain Check Constraints.
-- ====================================================================

-- 1. UNIVERSITY1143 (Campus Institutions)
CREATE TABLE UNIVERSITY1143 (
    UNID NUMBER PRIMARY KEY,
    UNAME VARCHAR2(100) NOT NULL,
    LOCATION VARCHAR2(100)
);

-- 2. DEPARTMENT1143 (Academic Departments)
CREATE TABLE DEPARTMENT1143 (
    DEPT_ID NUMBER PRIMARY KEY,
    DEPT_NAME VARCHAR2(100) NOT NULL,
    UNID NUMBER NOT NULL,
    CONSTRAINT FK_DEPT_UNID FOREIGN KEY (UNID) REFERENCES UNIVERSITY1143(UNID)
);

-- 3. FACULTY1143 (Teaching Faculty)
CREATE TABLE FACULTY1143 (
    FID NUMBER PRIMARY KEY,
    FNAME VARCHAR2(100) NOT NULL,
    DESIGNATION VARCHAR2(100),
    SALARY NUMBER CHECK (SALARY > 0),
    DEPT_ID NUMBER,
    CONSTRAINT FK_FACULTY_DEPT FOREIGN KEY (DEPT_ID) REFERENCES DEPARTMENT1143(DEPT_ID)
);

-- 4. STUDENT1143 (Enrolled Student Cohort)
CREATE TABLE STUDENT1143 (
    SID NUMBER PRIMARY KEY,
    SNAME VARCHAR2(100) NOT NULL,
    DOB DATE,
    GENDER CHAR(1) CHECK (GENDER IN ('M', 'F', 'O')),
    ADDRESS VARCHAR2(255),
    DEPT_ID NUMBER,
    CONSTRAINT FK_STUDENT_DEPT FOREIGN KEY (DEPT_ID) REFERENCES DEPARTMENT1143(DEPT_ID)
);

-- 5. COURSE1143 (Curriculum Course Catalog)
CREATE TABLE COURSE1143 (
    COURSE_ID NUMBER PRIMARY KEY,
    COURSE_NAME VARCHAR2(100) NOT NULL,
    CREDITS NUMBER CHECK (CREDITS > 0),
    DEPT_ID NUMBER,
    FID NUMBER,
    CONSTRAINT FK_COURSE_DEPT FOREIGN KEY (DEPT_ID) REFERENCES DEPARTMENT1143(DEPT_ID),
    CONSTRAINT FK_COURSE_FID FOREIGN KEY (FID) REFERENCES FACULTY1143(FID)
);

-- 6. CLASSROOM1143 (Lecture & Laboratory Halls)
CREATE TABLE CLASSROOM1143 (
    ROOM_NO NUMBER PRIMARY KEY,
    CAPACITY NUMBER CHECK (CAPACITY > 0),
    DEPT_ID NUMBER,
    CONSTRAINT FK_CLASSROOM_DEPT FOREIGN KEY (DEPT_ID) REFERENCES DEPARTMENT1143(DEPT_ID)
);

-- 7. EXAM1143 (Scheduled Evaluations)
CREATE TABLE EXAM1143 (
    EXAM_ID NUMBER PRIMARY KEY,
    EXAM_NAME VARCHAR2(100) NOT NULL,
    EXAM_DATE DATE NOT NULL,
    COURSE_ID NUMBER,
    ROOM_NO NUMBER,
    CONSTRAINT FK_EXAM_COURSE FOREIGN KEY (COURSE_ID) REFERENCES COURSE1143(COURSE_ID),
    CONSTRAINT FK_EXAM_ROOM FOREIGN KEY (ROOM_NO) REFERENCES CLASSROOM1143(ROOM_NO)
);

-- 8. RESULT1143 (Academic Grading & Evaluations)
CREATE TABLE RESULT1143 (
    RESULT_ID NUMBER PRIMARY KEY,
    GRADE CHAR(2) CHECK (GRADE IN ('S', 'A', 'B', 'C', 'D', 'E', 'F')),
    MARKS NUMBER CHECK (MARKS BETWEEN 0 AND 100),
    SID NUMBER,
    EXAM_ID NUMBER,
    CONSTRAINT FK_RESULT_STUDENT FOREIGN KEY (SID) REFERENCES STUDENT1143(SID),
    CONSTRAINT FK_RESULT_EXAM FOREIGN KEY (EXAM_ID) REFERENCES EXAM1143(EXAM_ID)
);

-- 9. LIBRARY1143 (Academic Reference Books)
CREATE TABLE LIBRARY1143 (
    BOOK_ID NUMBER PRIMARY KEY,
    TITLE VARCHAR2(100) NOT NULL,
    AUTHOR VARCHAR2(100) NOT NULL,
    UNID NUMBER,
    CONSTRAINT FK_LIBRARY_UNID FOREIGN KEY (UNID) REFERENCES UNIVERSITY1143(UNID)
);

-- 10. HOSTEL1143 (Residential Student Blocks)
CREATE TABLE HOSTEL1143 (
    HOSTEL_ID NUMBER PRIMARY KEY,
    HOSTEL_NAME VARCHAR2(100) NOT NULL,
    CAPACITY NUMBER CHECK (CAPACITY > 0),
    UNID NUMBER,
    CONSTRAINT FK_HOSTEL_UNID FOREIGN KEY (UNID) REFERENCES UNIVERSITY1143(UNID)
);

